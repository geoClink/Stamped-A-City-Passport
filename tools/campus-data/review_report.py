"""Writes docs/campus-review-2.5.md: a checklist for a person to review the campus data before release.

For every campus it lists the school colors, the traditions (with their sources), and the
buildings worth a second look: unknown architect or style, or placed by a shared article.
Run with: python3 review_report.py
"""

import json
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent
REPO_ROOT = TOOL_DIR.parent.parent
OUTPUT = REPO_ROOT / "docs" / "campus-review-2.5.md"
CONFERENCE_NAMES = {"bigTen": "Big Ten", "sec": "SEC", "acc": "ACC", "big12": "Big 12", "ivyLeague": "Ivy League"}


def load_campuses() -> list[dict]:
    campuses = []
    for path in sorted((TOOL_DIR / "campuses").glob("*.json")):
        campuses.extend(json.loads(path.read_text()))
    return campuses


def group_name(campus: dict) -> str:
    if campus.get("conference"):
        return CONFERENCE_NAMES[campus["conference"]]
    return "Other U.S. campuses" if campus["country"] == "unitedStates" else "Outside the U.S."


def campus_section(campus: dict) -> list[str]:
    lines = [f"### {campus['name']}", ""]
    colors = campus.get("colors", [])
    lines.append(f"- [ ] Colors: {', '.join(f'`{c}`' for c in colors) if colors else '**none yet**'}")

    traditions = campus.get("traditions", [])
    if not traditions:
        lines.append("- [ ] Traditions: **none yet**")
    for tradition in traditions:
        lines.append(f"- [ ] Tradition: **{tradition['name']}**: {tradition['description']} ([source]({tradition['source']}))")

    for building in campus["buildings"]:
        notes = []
        if building.get("architect", "").strip().lower() == "unknown":
            notes.append("architect unknown")
        if building.get("buildingStyle", "").strip().lower() == "unknown":
            notes.append("style unknown")
        if building.get("sharedArticle"):
            notes.append(f"placed by a shared article ({building['wiki']})")
        if notes:
            lines.append(f"- [ ] Building: {building['name']}: {', '.join(notes)}")
    lines.append("")
    return lines


def main() -> None:
    campuses = load_campuses()
    traditions = sum(len(c.get("traditions", [])) for c in campuses)
    lines = [
        "# Campus data review (2.5)",
        "",
        "Generated by `tools/campus-data/review_report.py`; re-run it after changing the campus data.",
        "",
        f"{len(campuses)} campuses, {traditions} traditions. Check each box once you've looked at it.",
        "For traditions, make sure each one is safe, open to visitors, and not hurtful to another school.",
        "",
    ]
    # Hand-written notes from the research (what couldn't be confirmed, what was removed and why)
    flags = TOOL_DIR / "review_flags.md"
    if flags.exists():
        lines += [flags.read_text().strip(), ""]
    order = ["Big Ten", "SEC", "ACC", "Big 12", "Ivy League", "Other U.S. campuses", "Outside the U.S."]
    for group in order:
        members = sorted((c for c in campuses if group_name(c) == group), key=lambda c: c["name"])
        if not members:
            continue
        lines += [f"## {group}", ""]
        for campus in members:
            lines += campus_section(campus)
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}: {len(campuses)} campuses, {traditions} traditions")


if __name__ == "__main__":
    main()
