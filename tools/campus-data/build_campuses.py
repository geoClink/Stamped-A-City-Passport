"""Build the "Campus Architecture" collection from the JSON files in campuses/.

Each campus file lists campuses and their standout buildings. This script:

1. Checks every campus and building (required fields, unique ids, real country, 4+ buildings).
2. Looks up each building's coordinates from its Wikipedia article (or uses a hand-checked
   `coordinates` value from OpenStreetMap), and checks each building is within 2 km of its campus.
3. Writes the app data (unless --check is passed):
   - BuildingRegistry.json and CityDetails.json: campus entries are appended at the end of the
     file, so existing cities are never reformatted (keeps merges with other branches clean).
   - Model.swift and CityCoordinates.swift: the lines between the "BEGIN CAMPUSES" and
     "END CAMPUSES" markers are replaced.
   - Models/CampusList.swift: the set of campuses and the Wikipedia photo titles.

Run from this folder:
    python build_campuses.py --check      # check only, writes nothing
    python build_campuses.py              # check, then write the app files
"""

import argparse
import json
import math
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent
REPO_ROOT = TOOL_DIR.parent.parent
APP_DIR = REPO_ROOT / "Stamped! A City Passport"
REGISTRY_PATH = APP_DIR / "Resources" / "BuildingRegistry.json"
DETAILS_PATH = APP_DIR / "Resources" / "CityDetails.json"
MODEL_PATH = APP_DIR / "Models" / "Model.swift"
COORDINATES_PATH = APP_DIR / "Models" / "CityCoordinates.swift"
CAMPUS_LIST_PATH = APP_DIR / "Models" / "CampusList.swift"
CAMPUS_FOLDER = TOOL_DIR / "campuses"
CACHE_PATH = TOOL_DIR / "wiki_coordinates.json"
TRANSLATION_FOLDER = TOOL_DIR / "translations"  # e.g. translations/de.json

MAX_KM_FROM_CAMPUS = 2.0
MIN_BUILDINGS = 4  # the quiz needs at least 4 mappable landmarks per city
GENERATED_NOTE = "generated by tools/campus-data/build_campuses.py"

DETAIL_FIELDS = [
    "nickname", "airportName", "airportCode", "funFact", "language", "airportInfo",
    "languageInfo", "currencyInfo", "currencyCode", "transportation", "transportationFact",
]
# Campus detail fields that are translated; the rest (airport name/code, currency code) stay as-is
TRANSLATED_FIELDS = [
    "nickname", "airportInfo", "funFact", "language", "languageInfo",
    "currencyInfo", "transportation", "transportationFact",
]
TEXT_FIELDS = ["id", "wiki", "name", "description", "architect", "address", "oldUse", "newUse", "buildingStyle"]


# MARK: - Small helpers

def distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Great-circle distance between two points (haversine formula)."""
    earth_radius_km = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    delta_phi = math.radians(lat2 - lat1)
    delta_lambda = math.radians(lon2 - lon1)
    a = math.sin(delta_phi / 2) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(delta_lambda / 2) ** 2
    return 2 * earth_radius_km * math.asin(math.sqrt(a))


def country_cases() -> set[str]:
    """Case names of CityLocation.Country, read from Model.swift (e.g. "unitedStates")."""
    source = MODEL_PATH.read_text()
    country_block = source.split("enum Country")[1].split("var continent")[0]
    return set(re.findall(r"(?:case|,)\s*(\w+)\s*=\s*\"", country_block))


def existing_cities() -> dict[str, str]:
    """Enum case name -> name of every CityLocation.City that is not a campus."""
    source = strip_generated(MODEL_PATH.read_text())
    city_block = source.split("enum City:")[1].split("var id:")[0]
    return dict(re.findall(r"(?:case|,)\s*(\w+)\s*=\s*\"([^\"]+)\"", city_block))


def strip_generated(source: str) -> str:
    """Remove every generated campus block, so we only see the hand-written code."""
    return re.sub(r"[ \t]*// BEGIN CAMPUSES.*?// END CAMPUSES\n", "", source, flags=re.DOTALL)


def load_campuses() -> list[dict]:
    campuses: list[dict] = []
    for path in sorted(CAMPUS_FOLDER.glob("*.json")):
        for campus in json.loads(path.read_text()):
            campus["_file"] = path.name
            campuses.append(campus)
    return campuses


# MARK: - Wikipedia coordinates

def fetch_with_retry(request: urllib.request.Request, attempts: int = 6) -> dict:
    """Fetch JSON, waiting and retrying when Wikipedia says "too many requests" (HTTP 429)."""
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                return json.load(response)
        except urllib.error.HTTPError as error:
            if error.code != 429 or attempt == attempts - 1:
                raise
            wait_seconds = 5 * 2 ** attempt  # 5, 10, 20, 40... seconds
            print(f"  Wikipedia says too many requests; waiting {wait_seconds}s")
            time.sleep(wait_seconds)
    raise RuntimeError("unreachable")


def fetch_wiki_coordinates(titles: list[str], cache: dict) -> None:
    """Fill `cache` with title -> [lat, lon] (or None when the article has no coordinates)."""
    missing = sorted({title for title in titles if title not in cache})
    for start in range(0, len(missing), 50):
        batch = missing[start:start + 50]
        params = urllib.parse.urlencode({
            # colimit=max: without it Wikipedia returns coordinates for only 10 pages per request
            "action": "query", "prop": "coordinates", "coprimary": "primary", "colimit": "max",
            "redirects": 1, "format": "json", "titles": "|".join(batch),
        })
        request = urllib.request.Request(
            f"https://en.wikipedia.org/w/api.php?{params}",
            headers={"User-Agent": "StampedCampusCheck/1.0 (George Clinkscales app data check)"},
        )
        data = fetch_with_retry(request)["query"]

        # Wikipedia may rename the title (normalize / redirect); map results back to our titles
        renamed: dict[str, str] = {}
        for step in data.get("normalized", []) + data.get("redirects", []):
            renamed[step["from"]] = step["to"]
        found: dict[str, list[float] | None] = {}
        for page in data.get("pages", {}).values():
            coordinates = page.get("coordinates")
            found[page["title"]] = [coordinates[0]["lat"], coordinates[0]["lon"]] if coordinates else None
        for title in batch:
            final_title = title
            while final_title in renamed:
                final_title = renamed[final_title]
            cache[title] = found.get(final_title)
        time.sleep(0.5)  # be polite to the Wikipedia API


# MARK: - Checks

def check_campuses(campuses: list[dict], cache: dict) -> tuple[list[str], list[str]]:
    """Returns (errors, warnings). Also stores each building's final coordinates in `_lat`/`_lon`."""
    errors: list[str] = []
    warnings: list[str] = []
    countries = country_cases()
    cities = existing_cities()
    registry = json.loads(REGISTRY_PATH.read_text())
    campus_names = {campus.get("name") for campus in campuses}
    # Ids already used by the 140 real cities (campus entries from an earlier run don't count)
    city_ids = {b["id"] for city, buildings in registry.items() if city not in campus_names for b in buildings}

    seen_cases: set[str] = set()
    seen_names: set[str] = set()
    seen_ids: set[str] = set()

    for campus in campuses:
        label = f"{campus.get('name', '?')} ({campus['_file']})"
        for field in ["name", "enumCase", "country", "wiki", "currency", "details", "buildings"]:
            if not campus.get(field):
                errors.append(f"{label}: missing '{field}'")
        if errors and errors[-1].startswith(label):
            continue

        if campus["country"] not in countries:
            errors.append(f"{label}: country '{campus['country']}' is not a CityLocation.Country case")
        if campus["enumCase"] in cities or campus["enumCase"] in seen_cases:
            errors.append(f"{label}: enum case '{campus['enumCase']}' is already used")
        if not re.fullmatch(r"[a-z][A-Za-z0-9]*", campus["enumCase"]):
            errors.append(f"{label}: enum case '{campus['enumCase']}' should be lowerCamelCase")
        if campus["name"] in cities.values():
            errors.append(f"{label}: name clashes with an existing city")
        if campus["name"] in seen_names:
            errors.append(f"{label}: duplicate campus name")
        seen_cases.add(campus["enumCase"])
        seen_names.add(campus["name"])

        for field in DETAIL_FIELDS:
            if not str(campus["details"].get(field, "")).strip():
                errors.append(f"{label}: details.{field} is empty")

        buildings = campus["buildings"]
        if len(buildings) < MIN_BUILDINGS:
            errors.append(f"{label}: only {len(buildings)} buildings (need {MIN_BUILDINGS}+ for the quiz)")

        for building in buildings:
            building_label = f"{campus['name']} / {building.get('name', '?')}"
            for field in TEXT_FIELDS:
                if not str(building.get(field, "")).strip():
                    errors.append(f"{building_label}: '{field}' is empty")
            building_id = building.get("id", "")
            if not re.fullmatch(r"campus_[a-z0-9_]+", building_id):
                errors.append(f"{building_label}: id '{building_id}' should look like campus_school_building")
            if building_id in seen_ids or building_id in city_ids:
                errors.append(f"{building_label}: duplicate id '{building_id}'")
            seen_ids.add(building_id)
            year = building.get("yearBuilt", 0)
            if not isinstance(year, int) or not 1000 <= year <= 2026:
                errors.append(f"{building_label}: yearBuilt {year} looks wrong")
            if not isinstance(building.get("numberOfStories", 0), int):
                errors.append(f"{building_label}: numberOfStories must be a whole number (0 = unknown)")
            if not isinstance(building.get("foodSpots", []), list):
                errors.append(f"{building_label}: foodSpots must be a list")

            # Coordinates: Wikipedia first; a hand-checked OSM value only when the article has none.
            # "sharedArticle": true means `wiki` covers a whole group of buildings (e.g. a historic
            # district), so its coordinates are the group's, not this building's: use the OSM value.
            shared_article = building.get("sharedArticle", False)
            wiki_point = None if shared_article else cache.get(building.get("wiki", ""))
            manual_point = building.get("coordinates")
            if manual_point and not building.get("coordinatesSource"):
                errors.append(f"{building_label}: 'coordinates' needs a 'coordinatesSource' (e.g. an OSM link)")
            if shared_article and not manual_point:
                errors.append(f"{building_label}: 'sharedArticle' buildings need hand-checked 'coordinates'")
            point = wiki_point or manual_point
            if wiki_point and manual_point and distance_km(*wiki_point, *manual_point) > 0.3:
                warnings.append(
                    f"{building_label}: Wikipedia and the hand-checked coordinates are "
                    f"{distance_km(*wiki_point, *manual_point):.2f} km apart (using Wikipedia)"
                )
            if not point:
                errors.append(f"{building_label}: no coordinates on Wikipedia article '{building.get('wiki')}'")
                continue
            building["_lat"], building["_lon"] = round(point[0], 6), round(point[1], 6)

        located = [b for b in buildings if "_lat" in b]
        if not located:
            continue
        # Campus centre = average of its buildings (this is where the city list map centres)
        campus["_lat"] = round(sum(b["_lat"] for b in located) / len(located), 4)
        campus["_lon"] = round(sum(b["_lon"] for b in located) / len(located), 4)
        for building in located:
            km = distance_km(campus["_lat"], campus["_lon"], building["_lat"], building["_lon"])
            if km > MAX_KM_FROM_CAMPUS:
                errors.append(f"{campus['name']} / {building['name']}: {km:.2f} km from the campus centre")
        stacked = {(b["_lat"], b["_lon"]) for b in located}
        if len(stacked) < len(located):
            errors.append(f"{label}: two buildings share exactly the same coordinates")

        # The university's own article should be near the campus centre too
        university_point = cache.get(campus["wiki"])
        if university_point:
            km = distance_km(campus["_lat"], campus["_lon"], *university_point)
            if km > 3:
                warnings.append(f"{label}: campus centre is {km:.1f} km from the '{campus['wiki']}' article")
        else:
            warnings.append(f"{label}: '{campus['wiki']}' article has no coordinates to compare with")

    return errors, warnings


# MARK: - Writing the app files

def registry_entry(campus: dict, building: dict) -> dict:
    """A building in exactly the shape (and key order) BuildingRegistry.json uses."""
    return {
        "id": building["id"],
        "name": building["name"],
        "assetName": building["id"],  # no bundled image: photos come from Wikipedia
        "description": building["description"],
        "architect": building["architect"],
        "yearBuilt": building["yearBuilt"],
        "address": building["address"],
        "oldUse": building["oldUse"],
        "newUse": building["newUse"],
        "buildingStyle": building["buildingStyle"],
        "numberOfStories": building.get("numberOfStories", 0),
        "height": building.get("height", 0),
        "foodSpots": building.get("foodSpots", []),
        "currency": campus["currency"],
        "latitude": building["_lat"],
        "longitude": building["_lon"],
    }


def append_campus_entries(path: Path, new_entries: dict, campus_names: set[str]) -> None:
    """Append campus keys to the end of a top-level JSON object without touching other keys.

    Campus entries from an earlier run are always the last keys in the file, so we cut
    the file at the first one and write the fresh campus block after the real cities.
    """
    text = path.read_text()
    existing = json.loads(text)
    # Make sure no campus entry has been placed in the middle of the cities by hand
    keys = list(existing)
    first_campus = next((index for index, key in enumerate(keys) if key in campus_names), len(keys))
    if any(key not in campus_names for key in keys[first_campus:]):
        raise SystemExit(f"{path.name}: a city key comes after a campus key; fix the file by hand first")

    if first_campus < len(keys):
        marker = f',\n  {json.dumps(keys[first_campus], ensure_ascii=False)}: '
        base = text[:text.index(marker)]
    else:
        base = text[:text.rstrip().rindex("}")].rstrip()

    block = json.dumps(new_entries, indent=2, ensure_ascii=False)
    inner = block[1:-1].strip("\n")  # drop the outer { } but keep the 2-space indent
    path.write_text(f"{base},\n{inner}\n}}" if new_entries else f"{base}\n}}")

    # Safety check: real cities must be byte-for-byte unchanged
    rewritten = json.loads(path.read_text())
    for key in keys[:first_campus]:
        if rewritten[key] != existing[key]:
            raise SystemExit(f"{path.name}: '{key}' changed while appending campuses")


def replace_generated_block(path: Path, anchor: str, indent: str, lines: list[str]) -> None:
    """Put `lines` between BEGIN/END CAMPUSES markers right after the `anchor` line."""
    source = path.read_text()
    if anchor not in source:
        raise SystemExit(f"{path.name}: can't find the line '{anchor.strip()}' to add campuses after")
    # Remove only the old block that follows this anchor (a file can have several blocks)
    old_block = re.compile(re.escape(anchor) + r"[ \t]*// BEGIN CAMPUSES.*?// END CAMPUSES\n", re.DOTALL)
    source = old_block.sub(lambda match: anchor, source, count=1)
    block = [f"{indent}// BEGIN CAMPUSES ({GENERATED_NOTE})"] + [f"{indent}{line}" for line in lines]
    block.append(f"{indent}// END CAMPUSES")
    path.write_text(source.replace(anchor, anchor + "\n".join(block) + "\n", 1))


def swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def load_translations(language: str) -> dict:
    """Campus name -> translated detail fields, from translations/<language>.json (empty if none yet)."""
    path = TRANSLATION_FOLDER / f"{language}.json"
    return json.loads(path.read_text()) if path.exists() else {}


def missing_translations(campuses: list[dict]) -> list[str]:
    """One warning per language that is missing campuses or fields."""
    warnings: list[str] = []
    for language_path in sorted(APP_DIR.glob("*.lproj/CityDetails.json")):
        language = language_path.parent.stem
        translations = load_translations(language)
        missing = [
            campus["name"] for campus in campuses
            if any(field not in translations.get(campus["name"], {}) for field in TRANSLATED_FIELDS)
        ]
        if missing:
            warnings.append(f"{language}: {len(missing)} campuses not fully translated (English is used)")
    return warnings


def write_app_files(campuses: list[dict]) -> None:
    campus_names = {campus["name"] for campus in campuses}

    registry_entries = {c["name"]: [registry_entry(c, b) for b in c["buildings"]] for c in campuses}
    append_campus_entries(REGISTRY_PATH, registry_entries, campus_names)
    detail_entries = {c["name"]: {key: c["details"][key] for key in sorted(DETAIL_FIELDS)} for c in campuses}
    append_campus_entries(DETAILS_PATH, detail_entries, campus_names)

    # Each language has its own CityDetails.json (e.g. de.lproj); without a campus entry there,
    # the campus page shows placeholder details in that language. Missing translations fall back to English.
    for language_path in sorted(APP_DIR.glob("*.lproj/CityDetails.json")):
        language = language_path.parent.stem  # "de", "zh-Hans"...
        translations = load_translations(language)
        localized_entries = {}
        for name, details in detail_entries.items():
            translated = translations.get(name, {})
            localized_entries[name] = {
                key: translated.get(key, value) if key in TRANSLATED_FIELDS else value
                for key, value in details.items()
            }
        append_campus_entries(language_path, localized_entries, campus_names)

    # City enum cases
    case_lines = [f'case {c["enumCase"]} = {swift_string(c["name"])}' for c in campuses]
    replace_generated_block(MODEL_PATH, '        case dhaka = "Dhaka"\n', "        ", case_lines)

    # Country switch: one line per country
    by_country: dict[str, list[str]] = {}
    for campus in campuses:
        by_country.setdefault(campus["country"], []).append(f".{campus['enumCase']}")
    country_lines = [f"case {', '.join(cases)}: return .{country}" for country, cases in sorted(by_country.items())]
    replace_generated_block(MODEL_PATH, "            case .dhaka: return .bangladesh\n", "            ", country_lines)

    # Map centre of each campus
    width = max(len(c["enumCase"]) for c in campuses) + 2
    coordinate_lines = [
        f"case .{(c['enumCase'] + ':').ljust(width)}return ({c['_lat']:.4f}, {c['_lon']:.4f})" for c in campuses
    ]
    replace_generated_block(
        COORDINATES_PATH, "        case .queenstown:       return (-45.0312, 168.6626)\n", "        ", coordinate_lines
    )

    # Campus set + photo titles (only where the app name isn't the article title)
    case_list = "\n".join(f"        .{c['enumCase']}," for c in campuses)
    overrides = "\n".join(
        f"        {swift_string(b['id'])}: {swift_string(b['wiki'])},"
        # A shared article would give every building in the group the same photo, so skip those
        for c in campuses for b in c["buildings"] if b["wiki"] != b["name"] and not b.get("sharedArticle")
    ) or "        :"
    CAMPUS_LIST_PATH.write_text(f"""//
//  CampusList.swift
//  Stamped! A City Passport
//
//  Do not edit by hand: this file is {GENERATED_NOTE}.
//  Edit the campus JSON in tools/campus-data/campuses and re-run the script.
//

import Foundation

extension CityLocation.City {{
    /// Every campus in the "Campus Architecture" collection.
    static let campuses: Set<CityLocation.City> = [
{case_list}
    ]
}}

extension WikimediaService {{
    /// Building ID → Wikipedia article title, for campus buildings whose app name
    /// isn't the exact article title.
    nonisolated static let campusTitleOverrides: [String: String] = [
{overrides}
    ]
}}
""")


# MARK: - Main

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check the campus files; write nothing")
    parser.add_argument("--only", help="check just this campus file (e.g. campuses/us_northeast.json)")
    args = parser.parse_args()

    campuses = load_campuses()
    if args.only:
        only_name = Path(args.only).name
        checked = [c for c in campuses if c["_file"] == only_name]
    else:
        checked = campuses

    cache: dict = json.loads(CACHE_PATH.read_text()) if CACHE_PATH.exists() else {}
    titles = [c.get("wiki", "") for c in checked] + [b.get("wiki", "") for c in checked for b in c.get("buildings", [])]
    fetch_wiki_coordinates([t for t in titles if t], cache)
    if not args.check:
        CACHE_PATH.write_text(json.dumps(dict(sorted(cache.items())), indent=2, ensure_ascii=False) + "\n")

    errors, warnings = check_campuses(campuses if not args.only else checked, cache)
    warnings += missing_translations(campuses)
    building_count = sum(len(c.get("buildings", [])) for c in checked)
    print(f"Checked {len(checked)} campuses, {building_count} buildings")
    for warning in warnings:
        print(f"  warning: {warning}")
    for error in errors:
        print(f"  ERROR: {error}")
    if errors:
        print(f"{len(errors)} errors: nothing written")
        return 1
    if args.check:
        print("All good (check only, nothing written)")
        return 0

    write_app_files(campuses)
    print(f"Wrote {len(campuses)} campuses to the registry, city details and Swift files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
